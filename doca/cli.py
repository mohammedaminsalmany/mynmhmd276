def _write_file(path: Path, content: str, *, force: bool) -> bool:
    if path.exists() and not force:
        return False
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    return True


def _humanize(stem: str) -> str:
    words = re.split(r"[-_\s]+", stem)
    return " ".join(word[:1].upper() + word[1:] for word in words if word) or stem


def cmd_init(args: argparse.Namespace) -> int:
    root = Path(args.path).resolve()
    root.mkdir(parents=True, exist_ok=True)
    docs = root / "docs"

    config = {
        "title": "Doca Docs",
        "description": "Documentation built with Doca — a modern docs-as-code engine.",
        "author": "",
        "docs_dir": "docs",
        "out_dir": "site",
        "lang": "en",
        "repo": "",
        "edit_url": "",
        "theme": {"accent": "#6366f1", "default": "auto"},
        "nav": [
            {"title": "Introduction", "path": "index.md"},
            {
                "title": "Guides",
                "items": [
                    {"title": "Getting started", "path": "getting-started.md"},
                    {"title": "Configuration", "path": "configuration.md"},
                ],
            },
        ],
        "footer": {"text": "", "links": []},
    }

    created: list[Path] = []
    skipped: list[Path] = []

    def place(path: Path, content: str) -> None:
        if _write_file(path, content, force=args.force):
            created.append(path)
        else:
            skipped.append(path)

    place(root / CONFIG_FILE, json.dumps(config, indent=2, ensure_ascii=False) + "\n")
    place(docs / "index.md", SAMPLE_INDEX)
    place(docs / "getting-started.md", SAMPLE_GETTING_STARTED)
    place(docs / "configuration.md", SAMPLE_CONFIGURATION)
    place(root / ".gitignore", GITIGNORE)

    print(f"Doca workspace ready in {root}")
    for path in created:
        print(f"  created  {path.relative_to(root)}")
    for path in skipped:
        print(f"  skipped  {path.relative_to(root)} (already exists, use --force)")
    print("\nNext steps:")
    print("  1. doca build     render the site into site/")
    print("  2. doca serve     preview at http://127.0.0.1:8000")
    print("  3. doca new page  add a new markdown page")
    return 0


def cmd_build(args: argparse.Namespace) -> int:
    root = Path(args.dir).resolve()
    started = time.perf_counter()
    result = build_site(root, out_dir=args.out)
    elapsed = (time.perf_counter() - started) * 1000
    if not args.quiet:
        try:
            display = result.out_dir.relative_to(root)
        except ValueError:
            display = result.out_dir
        pages = "page" if result.pages == 1 else "pages"
        print(f"Built {result.pages} {pages} in {elapsed:.0f} ms → {display}")
    return 0


class _DevHandler(http.server.SimpleHTTPRequestHandler):
    """Static file handler that falls back to Doca's 404 page."""

    def send_error(self, code: int, message: str | None = None, explain: str | None = None) -> None:
        if code == 404:
            page = Path(self.directory or ".") / "404.html"
            if page.exists():
                body = page.read_bytes()
                self.send_response(404)
                self.send_header("Content-Type", "text/html; charset=utf-8")
                self.send_header("Content-Length", str(len(body)))
                self.end_headers()
                if self.command != "HEAD":
                    self.wfile.write(body)
                return
        super().send_error(code, message, explain)

    def log_message(self, format: str, *args) -> None:  # noqa: A002 - stdlib signature
        sys.stderr.write("  %s\n" % (format % args))


def _snapshot(root: Path, docs_dir: Path) -> dict[str, float]:
    snapshot: dict[str, float] = {}
    for path in list(docs_dir.rglob("*")) + [root / CONFIG_FILE]:
        if path.is_file():
            try:
                snapshot[str(path)] = path.stat().st_mtime
            except OSError:
                continue
    return snapshot


def cmd_serve(args: argparse.Namespace) -> int:
    root = Path(args.dir).resolve()
    config = load_config(root)
    docs_dir = root / str(config.get("docs_dir") or "docs")
    out_dir = (root / str(config.get("out_dir") or "site")).resolve()

    result = build_site(root)
    print(f"Serving {result.pages} pages from {result.out_dir}")
    print(f"  → http://{args.host}:{args.port}")

    state = {"snapshot": _snapshot(root, docs_dir), "stop": False}

    def watch() -> None:
        while not state["stop"]:
            time.sleep(1.0)
            current = _snapshot(root, docs_dir)
            if current != state["snapshot"]:
                state["snapshot"] = current
                try:
                    rebuilt = build_site(root)
                    print(f"\n  ↻ rebuilt {rebuilt.pages} pages")
                except DocaError as exc:
                    print(f"\n  ! build failed: {exc}")

    if not args.no_watch:
        thread = threading.Thread(target=watch, name="doca-watch", daemon=True)
        thread.start()

    handler = functools.partial(_DevHandler, directory=str(out_dir))
    try:
        with http.server.ThreadingHTTPServer((args.host, args.port), handler) as server:
            if args.open:
                threading.Timer(
                    0.4, lambda: webbrowser.open(f"http://{args.host}:{args.port}")
                ).start()
            try:
                server.serve_forever()
            except KeyboardInterrupt:
                print("\nStopped.")
    finally:
        state["stop"] = True
    return 0


def cmd_new(args: argparse.Namespace) -> int:
    root = Path(args.dir).resolve()
    config = load_config(root)
    docs_dir = root / str(config.get("docs_dir") or "docs")

    name = args.name.strip()
    if name.lower().endswith(".md"):
        name = name[:-3]
    if not name:
        raise DocaError("Please provide a page name, for example: doca new guides/deploy")
    if name.startswith(("/", ".")) or ".." in Path(name).parts:
        raise DocaError("Page names must stay inside the documentation folder.")

    slug_parts = [slugify(part) for part in Path(name).parts if part not in ("", ".")]
    relative = Path(*slug_parts).with_suffix(".md")
    target = docs_dir / relative
    if target.exists() and not args.force:
        raise DocaError(f"{target.relative_to(root)} already exists (use --force to overwrite).")

    title = args.title or _humanize(slug_parts[-1])
    content = (
        "---\n"
        f"title: {title}\n"
        "description: \n"
        "---\n\n"
        f"# {title}\n\n"
        "Write your content here. Doca renders Markdown with headings, lists,\n"
        "tables, code blocks, block quotes and more.\n\n"
        "## Section\n\n"
        "Add your first section.\n"
    )
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content, encoding="utf-8")
    print(f"Created {target.relative_to(root)}")
    if config.get("nav"):
        print("Remember to add the page to the 'nav' array in doca.json.")
    return 0


def build_parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(
        prog="doca",
        description="Doca — a modern, lightweight docs-as-code engine.",
        epilog="Run 'doca <command> --help' for details on a command.",
    )
    parser.add_argument(
        "-V", "--version", action="version", version=f"doca {__version__}"
    )
    parser.add_argument(
        "-C", "--dir", default=".", help="project directory (default: current directory)"
    )
    subparsers = parser.add_subparsers(dest="command", metavar="<command>")

    init = subparsers.add_parser("init", help="scaffold a new documentation workspace")
    init.add_argument("path", nargs="?", default=".", help="where to create the workspace")
    init.add_argument("--force", action="store_true", help="overwrite existing files")

    build = subparsers.add_parser("build", help="render the site into static HTML")
    build.add_argument("-o", "--out", default=None, help="output directory (default: site/)")
    build.add_argument("-q", "--quiet", action="store_true", help="suppress output")

    serve = subparsers.add_parser("serve", help="build and preview the site locally")
    serve.add_argument("-p", "--port", type=int, default=8000, help="port to listen on")
    serve.add_argument("--host", default="127.0.0.1", help="host to bind (default: 127.0.0.1)")
    serve.add_argument("--no-watch", action="store_true", help="disable auto-rebuild")
    serve.add_argument("--open", action="store_true", help="open the site in a browser")

    new = subparsers.add_parser("new", help="create a new Markdown page")
    new.add_argument("name", help="page name or path, for example guides/deployment")
    new.add_argument("--title", default=None, help="page title (default derived from the name)")
    new.add_argument("--force", action="store_true", help="overwrite an existing page")

    return parser


def main(argv: Sequence[str] | None = None) -> int:
    parser = build_parser()
    args = parser.parse_args(argv)
    if not getattr(args, "command", None):
        parser.print_help()
        return 1

    handlers = {
        "init": cmd_init,
        "build": cmd_build,
        "serve": cmd_serve,
        "new": cmd_new,
    }
    try:
        return handlers[args.command](args)
    except DocaError as exc:
        print(f"doca: error: {exc}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("Stopped.", file=sys.stderr)
        return 130


if __name__ == "__main__":
    raise SystemExit(main())
